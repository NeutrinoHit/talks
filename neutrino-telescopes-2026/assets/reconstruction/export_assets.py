"""Rebuild public synthetic input + raw HTML fragment from authored TOML.

No raw telescope response or detector calibration is read. The initial sampled
event is generated by the same model and seed as the explanatory movie.
"""
from pathlib import Path
import html
import importlib.util
import json
import tomllib
from matplotlib import colormaps

HERE=Path(__file__).resolve().parent
SOURCE=HERE.parents[3]/'dvnanima'/'neutrino_reconstruction'


def export():
    with (HERE/'ui.toml').open('rb') as f: ui=tomllib.load(f)
    with (SOURCE/'config.toml').open('rb') as f: movie=tomllib.load(f)
    spec=importlib.util.spec_from_file_location('teaching_reconstruction',SOURCE/'model.py')
    model=importlib.util.module_from_spec(spec); spec.loader.exec_module(model)
    settings=model.load_settings(SOURCE/'physics.toml')
    event=model.generate(settings)
    settings['browser_fit']=ui['browser_fit']
    palette=lambda name: [[round(float(c)*255) for c in colormaps[name](i/(ui['canvas']['palette_samples']-1))[:3]] for i in range(ui['canvas']['palette_samples'])]
    data={'settings':settings,'event':event,'ui':ui,'camera':movie['camera'],
          'drawing':movie['drawing'],'style':{k:v for k,v in movie['style'].items() if k!='font'},
          'palettes':{'time':palette(movie['drawing']['time_palette']),'sky':palette(movie['drawing']['sky_palette'])}}
    (HERE/'data.json').write_text(json.dumps(data,indent=2,allow_nan=False)+'\n')
    esc=lambda value: html.escape(str(value),quote=True)
    layout=ui['layout']; copy=ui['copy']; controls=ui['controls']; p=settings['physics']; g=settings['generation']
    row_style=f"display:flex;flex-wrap:wrap;align-items:center;gap:{layout['controls_gap_em']}em;margin:{layout['row_margin_em']}em 0;font-size:{layout['controls_em']}em;"
    button_style=f"font:inherit;color:inherit;background:transparent;border:{layout['border_width_px']}px solid currentColor;border-radius:{layout['border_radius_px']}px;padding:{layout['button_padding_em'][0]}em {layout['button_padding_em'][1]}em;cursor:pointer;"
    buttons=''.join(f'<button type="button" data-action="{key}" style="{button_style}">{esc(copy[key])}</button>' for key in ['new_event','fit','reveal','reset'])
    def control(key,low,high,step,value,label):
        span_style=f'display:inline-block;flex:0 0 {layout["slider_label_width_em"][key]}em;width:{layout["slider_label_width_em"][key]}em;min-height:{layout["slider_label_height_em"]}em;white-space:nowrap;'
        input_style=f'font:inherit;flex:none;width:{layout["slider_width_em"]}em;height:{layout["slider_height_em"]}em;margin:0;touch-action:pan-y;'
        return f'<label title="{esc(label)}" style="display:inline-flex;align-items:center;gap:{layout["slider_label_gap_em"]}em;flex:none;"><span data-control-label="{key}" style="{span_style}"></span><input data-control="{key}" type="range" aria-label="{esc(label)}" min="{low}" max="{high}" step="{step}" value="{value}" style="{input_style}"></label>'
    trial=movie['drawing']['wrong_direction_deg']
    angle_controls=control('theta',*settings['fit']['theta_bounds_deg'],controls['theta_step_deg'],trial[0],copy['theta_aria'])+control('phi',*settings['fit']['phi_bounds_deg'],controls['phi_step_deg'],trial[1],copy['phi_aria'])
    inputs=esc(copy['next_event_label'])+control('budget',controls['budget_min'],controls['budget_max'],controls['budget_step'],g['expected_total_pe'],copy['budget_aria'])+control('sigma',controls['sigma_min_ns'],controls['sigma_max_ns'],controls['sigma_step_ns'],g['sigma_ns'],copy['sigma_aria'])+esc(copy['fit_model_label'])+control('group',controls['group_index_min'],controls['group_index_max'],controls['group_index_step'],p['n_group'],copy['group_aria'])
    overlays=[]
    for key,pos_key,is_math in [('scene_title','scene_label',False),('scene_legend','scene_legend',False),('sky_title','sky_title',False),('sky','sky_formula',True),('theta_axis','sky_theta_label',True),('phi_axis','sky_phi_label',True),('residual_title','residual_title',False),('residual_axis','residual_x_label',True),('histogram_axis','histogram_label',True),('time_axis','time_label',True),('scale','scale_position',True)]:
        pos=layout[pos_key] if pos_key in layout else ui['canvas'][pos_key]
        if key=='scale': pos=[pos[0],pos[1]-ui['canvas']['scale_label_y_offset']]
        overlays.append(f'<span data-plot-label="{key}" data-math="{str(is_math).lower()}" style="position:absolute;left:{pos[0]*100}%;top:{pos[1]*100}%;font-size:{layout["labels_em"]}em;pointer-events:none;"></span>')
    fragment=f'''<!-- Generated by export_assets.py from ui.toml and the public synthetic model. -->
<div data-reconstruction>
<div style="{row_style}">{buttons}{angle_controls}</div>
<div style="{row_style}" title="{esc(copy['budget_hint'])}">{inputs}</div>
<div data-plots style="position:relative;width:100%;">
<canvas width="{ui['canvas']['width']}" height="{ui['canvas']['height']}" style="display:block;width:100%;height:auto;" aria-label="{esc(copy['accessible_canvas'])}"></canvas>
{''.join(overlays)}
</div>
<div style="display:flex;flex-wrap:wrap;align-items:center;gap:{layout['controls_gap_em']}em;font-size:{layout['status_em']}em;margin:{layout['row_margin_em']}em 0;"><span data-fit-status>{esc(copy['loading'])}</span><span data-numeric-status></span><span data-truth-status></span></div>
<div class="muted" style="font-size:{layout['assumption_em']}em;"><span data-assumptions>{esc(copy['assumption'])}</span></div>
</div>
<script data-external="1" src="assets/reconstruction/model.js"></script>
<script data-external="1" src="assets/reconstruction/interactive.js"></script>
'''
    (HERE/'interactive.html').write_text(fragment)
    print(f'Exported public synthetic event: {sum(event["counts"])} PE, {len(event["positions_m"])} sensors')


if __name__=='__main__': export()
